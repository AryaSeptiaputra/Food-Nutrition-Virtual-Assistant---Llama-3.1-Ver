@app.post("/v1/upload/data")
async def upload_data(
    target: str = Form(...),
    file: Optional[UploadFile] = File(None),
    records: Optional[List[Dict]] = Body(None)
):
    """
    Appends new data to the existing CSV datasets (details or nutritions).
    Accepts data either as an uploaded CSV file or a list of JSON records.

    Args:
        target (str): The target file to update ('details' or 'nutritions').
        file (Optional[UploadFile]): A CSV file containing new rows to append.
        records (Optional[List[Dict]]): A JSON body containing a list of records to append.

    Returns:
        JSONResponse: A status message indicating the number of rows appended.

    Raises:
        HTTPException (400): If inputs are invalid (missing data, wrong format, header mismatch).
        HTTPException (500): If filesystem operations fail.
    """
    try:
        target_path = _get_raw_csv_path(target)
    except ValueError:
        raise HTTPException(status_code=400, detail="Invalid target. Use 'details' or 'nutritions'.")

    if not os.path.exists(os.path.dirname(target_path)):
        raise HTTPException(status_code=500, detail="Target directory configuration error.")

    if not file and not records:
        raise HTTPException(status_code=400, detail="Provide a CSV file or JSON records.")

    try:
        with open(target_path, "r", encoding="utf-8-sig") as f:
            reader = csv.reader(f)
            target_header = next(reader)
    except Exception:
        raise HTTPException(status_code=500, detail="Failed to read target CSV header.")

    rows_to_append = []

    if file:
        if not file.filename.lower().endswith(".csv"):
            raise HTTPException(status_code=400, detail="File must be a CSV.")
        
        content = await file.read()
        text = content.decode("utf-8")
        uploaded_io = io.StringIO(text)
        reader = csv.reader(uploaded_io)
        
        try:
            header = next(reader)
            if [h.strip() for h in header] != [h.strip() for h in target_header]:
                raise HTTPException(status_code=400, detail="CSV header mismatch.")
        except StopIteration:
            raise HTTPException(status_code=400, detail="Uploaded CSV is empty.")
            
        for row in reader:
            if any(cell.strip() for cell in row):
                rows_to_append.append(row)

    if records:
        for item in records:
            row = [str(item.get(col, "")) for col in target_header]
            if any(cell.strip() for cell in row):
                rows_to_append.append(row)

    if not rows_to_append:
        return JSONResponse(status_code=200, content={"status": "no_changes", "message": "No new data to append."})

    try:
        with open(target_path, "a", newline="", encoding="utf-8") as f:
            writer = csv.writer(f)
            writer.writerows(rows_to_append)
    except Exception as e:
        raise HTTPException(status_code=500, detail=f"Failed to write data: {e}")

    return JSONResponse(status_code=201, content={"status": "ok", "appended_count": len(rows_to_append)})

@app.post("/v1/admin/sync-knowledge", response_model=ETLResponse)
async def admin_sync_knowledge(background_tasks: BackgroundTasks):
    """
    Triggers the Extract-Transform-Load (ETL) pipeline in the background.

    This process synchronizes the Knowledge Base by reading the CSV data,
    generating embeddings, and updating the ChromaDB vector store.

    Args:
        background_tasks (BackgroundTasks): FastAPI utility for running tasks asynchronously.

    Returns:
        ETLResponse: Confirmation that the task has been accepted.
    """
    background_tasks.add_task(run_etl_pipeline)
    return ETLResponse(status="accepted", message="ETL Pipeline started in background.")

